const dicts: Record<Lang, Record<CustomerKey, string>> = { PT: pt, EN: en, ES: es, FR: fr }

export function t(
  lang: Lang,
  key: CustomerKey,
  params: Record<string, string | number> = {},
): string {
  let s = dicts[lang][key]
  for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v))
  return s
}
